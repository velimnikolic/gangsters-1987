        public static List<CoreLayout.Block> CreateBlocks()
        {
            var blocks = new List<CoreLayout.Block>(Entries.Length);
            for (int n = 0; n < Entries.Length; n++)
            {
                var entry = Entries[n];
                int cd = entry.NorthToSouth.Length;
                int cw = cd > 0 ? entry.NorthToSouth[0].Length : 0;
                var mask = new bool[cw, cd];
                for (int row = 0; row < cd; row++)
                {
                    var line = entry.NorthToSouth[row];
                    if (line.Length != cw)
                        throw new System.InvalidOperationException($"Core block {entry.Name} has a ragged baked mask.");
                    int j = cd - 1 - row;
                    for (int i = 0; i < cw; i++) mask[i, j] = line[i] == '#';
                }
                blocks.Add(CoreLayout.Describe(entry.Name, new Vector2(entry.X0, entry.Z0), cw, cd, mask, entry.MaxH));
            }
            return blocks;
        }

        public static int Count => Entries.Length;
